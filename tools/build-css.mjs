// Usage: node tools/build-css.mjs [--check]
// src/css/*.css are the sources; src/components.css is generated from them (the full kit in one file).
// Apps that need only part of the kit copy tokens.css + the modules they want (base.css is optional) instead.
import { readFileSync, writeFileSync } from 'node:fs';

const ORDER = ['base', 'controls', 'overlays', 'board', 'shelf', 'page'];
const banner = `/* ═══════════════════════════════════════
   nimbleUI — components (GENERATED by tools/build-css.mjs from src/css/*.css; edit those, not this file)
   Needs tokens.css first. Only colours come from tokens; nothing here depends on the theme.
   Modules: ${ORDER.join(', ')}.
   ═══════════════════════════════════════ */
`;
const out = banner + ORDER.map(m => '\n' + readFileSync(new URL(`../src/css/${m}.css`, import.meta.url), 'utf8').replace(/\r\n/g, '\n').trimEnd() + '\n').join('');
const target = new URL('../src/components.css', import.meta.url);
if (process.argv.includes('--check')) {
  const cur = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  if (cur !== out) { console.error('src/components.css is out of date: run node tools/build-css.mjs'); process.exit(1); }
  console.log('components.css is up to date'); process.exit(0);
}
writeFileSync(target, out);
console.log('wrote src/components.css (' + out.split('\n').length + ' lines)');
